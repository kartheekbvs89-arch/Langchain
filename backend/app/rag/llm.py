"""LLM client — uses OpenAI if API key is set, else a local template LLM."""

from __future__ import annotations

from typing import Any

from langchain_core.language_models import LLM
from langchain_core.outputs import Generation, LLMResult
from pydantic import PrivateAttr

from app.config import is_openai_enabled, settings


# ---------------------------------------------------------------------------
# Local template LLM (no API key required)
# ---------------------------------------------------------------------------


class TemplateLLM(LLM):
    """A deterministic, contextual LLM that produces grounded answers.

    Used as a fallback when no OpenAI API key is configured. It does NOT call
    any external service — it composes an answer by stitching together the
    retrieved context chunks. This makes the entire backend runnable locally
    for demos and Phase 2 evaluation.
    """

    def _llm_type(self) -> str:
        return "template-llm"

    def _call(self, prompt: str, stop: list[str] | None = None, **kwargs: Any) -> str:
        """Parse the prompt and produce a grounded answer.

        The prompt format follows LangChain's chat template:
            System: <system prompt>
            Context: <chunks>
            Question: <user question>
        """
        # Extract sections
        system = ""
        context = ""
        question = ""

        if "Question:" in prompt:
            question = prompt.split("Question:")[-1].strip()
        if "Context:" in prompt:
            ctx_part = prompt.split("Context:")[-1]
            if "Question:" in ctx_part:
                context = ctx_part.split("Question:")[0].strip()
            else:
                context = ctx_part.strip()
        if "System:" in prompt:
            sys_part = prompt.split("System:")[-1]
            if "Context:" in sys_part:
                system = sys_part.split("Context:")[0].strip()
            else:
                system = sys_part.strip()

        if not context:
            return (
                "I couldn't find relevant information in the knowledge base "
                "to answer this question. Please try rephrasing, or contact "
                "the relevant department directly."
            )

        # Parse context chunks (each chunk separated by ---, with source metadata)
        chunks = _parse_chunks(context)
        if not chunks:
            # Fallback: just use the raw context
            return _compose_answer(question, [context], ["knowledge base"])

        snippets = [c["text"] for c in chunks]
        sources = [c["source"] for c in chunks]

        return _compose_answer(question, snippets, sources)


def _parse_chunks(context: str) -> list[dict[str, str]]:
    """Parse context chunks from the prompt."""
    chunks = []
    # Try splitting on "Document:" or "[Source:" patterns
    parts = context.split("---")
    for part in parts:
        part = part.strip()
        if not part:
            continue
        source = "knowledge base"
        text = part
        # Look for source attribution
        if "Source:" in part:
            pieces = part.split("Source:", 1)
            text = pieces[0].strip()
            source = pieces[1].strip().split("\n")[0].strip()
        elif "[Source:" in part:
            pieces = part.split("[Source:", 1)
            text = pieces[0].strip()
            source = pieces[1].rstrip("]").strip()
        chunks.append({"text": text, "source": source})
    return chunks


def _compose_answer(question: str, snippets: list[str], sources: list[str]) -> str:
    """Compose a grounded answer from retrieved snippets."""
    # Take the top 2 most relevant snippets (assume already ranked)
    used = snippets[:2]
    used_sources = sources[:2]

    # Build a synthesized answer
    answer_parts = [
        f"Based on the retrieved knowledge base, here's what I found regarding \"{question}\":",
    ]
    for i, snippet in enumerate(used, 1):
        # Take first ~200 chars of each snippet
        short = snippet[:200].rstrip() + ("..." if len(snippet) > 200 else "")
        answer_parts.append(f"\n{i}. {short}")

    # Build citation list
    answer_parts.append("\n\nSources:")
    for src in used_sources:
        answer_parts.append(f"  • {src}")

    answer_parts.append(
        "\n\nNote: This response was generated by the local TemplateLLM (Phase 2 fallback). "
        "Set OPENAI_API_KEY in backend/.env to enable real LLM-powered answers."
    )
    return "\n".join(answer_parts)


# ---------------------------------------------------------------------------
# LLM factory
# ---------------------------------------------------------------------------


def get_llm() -> Any:
    """Return the configured LLM.

    - If OPENAI_API_KEY is set → use OpenAI (langchain_openai.ChatOpenAI)
    - Else → use TemplateLLM (local, no external calls)
    """
    if is_openai_enabled():
        try:
            from langchain_openai import ChatOpenAI

            return ChatOpenAI(
                model=settings.openai_model,
                temperature=settings.llm_temperature,
                max_tokens=settings.llm_max_tokens,
            )
        except Exception as e:
            print(f"[warn] OpenAI init failed, falling back to TemplateLLM: {e}")

    return TemplateLLM()


def llm_provider_name() -> str:
    return "openai" if is_openai_enabled() else "template-llm-local"
